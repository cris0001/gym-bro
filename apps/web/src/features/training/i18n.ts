// Polish plural: 1 → one, 2–4 (not 12–14) → few, else many.
const plPlural = (n: number, one: string, few: string, many: string) => {
  if (n === 1) return one;
  const tens = n % 100;
  const units = n % 10;
  return units >= 2 && units <= 4 && (tens < 12 || tens > 14) ? few : many;
};

